import assert from "node:assert/strict";
import test from "node:test";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import vm from "node:vm";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const builder = path.join(root, "scripts/build-landing-runtime.mjs");
const passport = path.join(root, "tests/fixtures/galiley.project-passport.draft.json");
const marketing = path.join(root, "tests/fixtures/canonical-runtime-marketing.json");

function readProfile(file) {
  const source = fs.readFileSync(file, "utf8");
  const context = { window: {} };
  vm.runInNewContext(source, context, { timeout: 1000 });
  return context.window.KEY_PROJECT;
}

test("canonical CLI emits the browser runtime contract and supports the exact runtime target", () => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), "key-runtime-"));
  const output = path.join(temp, "project.config.js");
  const command = args => execFileSync(process.execPath, [builder, "--passport", passport, "--marketing", marketing, ...args], {
    cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"]
  });

  try {
    const result = command(["--out", output]);
    const profile = readProfile(output);
    assert.equal(profile.project.id, "galiley-voronezh");
    assert.equal(profile.project.name, "ЖК «Галилей»");
    assert.equal(profile.marketing.headline, "Проверьте, подходит ли вам ЖК «Галилей»");
    assert.equal(profile.mode, "demo");
    assert.equal(profile.integration.leadEndpoint, "");
    assert.equal(profile.analytics.enabled, false);
    assert.ok(Array.isArray(profile.composition));
    assert.match(result, /Built galiley-voronezh in demo mode/);

    const runtimeConfig = path.join(root, "landing/runtime/project.config.js");
    const original = fs.readFileSync(runtimeConfig, "utf8");
    try {
      command(["--target-runtime"]);
      const targeted = readProfile(runtimeConfig);
      assert.equal(targeted.project.id, "galiley-voronezh");
      assert.equal(targeted.marketing.headline, profile.marketing.headline);
      assert.match(fs.readFileSync(runtimeConfig, "utf8"), /Generated by scripts\/build-landing-runtime\.mjs/);
    } finally {
      fs.writeFileSync(runtimeConfig, original);
    }
  } finally {
    fs.rmSync(temp, { recursive: true, force: true });
  }
});
